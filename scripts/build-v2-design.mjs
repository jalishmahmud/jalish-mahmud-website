import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import postcss from "postcss";

const sourceDirectory = path.join(process.cwd(), "styles", "v2-source");
const output = path.join(process.cwd(), "public", "design-v2.css");
const modules = [
  ["legal", "legal"],
  ["blog-index", "blog-index"],
  ["blog-post", "blog-post"],
  ["Blog", "Blog"],
  ["BlogShare", "BlogShare"],
  ["Contact", "Contact"],
  ["Education", "Education"],
  ["Experience", "Experience"],
  ["Footer", "Footer"],
  ["Gallery", "Gallery"],
  ["Header", "Header"],
  ["Hero", "Hero"],
  ["Projects", "Projects"],
  ["SectionHeader", "SectionHeader"],
  ["Skills", "Skills"],
  ["ThemeToggle", "ThemeToggle"],
];

function splitSelectors(selector) {
  const parts = [];
  let depth = 0;
  let start = 0;
  for (let index = 0; index < selector.length; index += 1) {
    if (selector[index] === "(") depth += 1;
    if (selector[index] === ")") depth -= 1;
    if (selector[index] === "," && depth === 0) {
      parts.push(selector.slice(start, index));
      start = index + 1;
    }
  }
  parts.push(selector.slice(start));
  return parts;
}

function scopeSelector(selector, namespace) {
  const globals = [];
  let scoped = selector.replace(/:global\(([^)]*)\)/g, (_, value) => {
    globals.push(value);
    return `__V2_GLOBAL_${globals.length - 1}__`;
  });
  if (namespace) {
    scoped = scoped.replace(/\.([a-zA-Z_][\w-]*)/g, (_, name) => `.design-${namespace}-${name}`);
  }
  scoped = scoped.replace(/__V2_GLOBAL_(\d+)__/g, (_, index) => globals[Number(index)]);
  scoped = scoped.trim();
  if (scoped.startsWith(":root")) return scoped.replace(/^:root/, 'html[data-design="v2"]');
  if (scoped.startsWith("html")) return scoped.replace(/^html/, 'html[data-design="v2"]');
  return `html[data-design="v2"] ${scoped}`;
}

async function transform(file, namespace) {
  const root = postcss.parse(await readFile(path.join(sourceDirectory, `${file}.css`), "utf8"));
  // Keep both designs' type scale and line spacing in one place: Classic CSS.
  // V2 retains every other visual and layout rule from its source styles.
  root.walkDecls(/^(font-size|line-height|font)$/, (declaration) => declaration.remove());
  root.walkRules((rule) => {
    if (rule.parent.type === "atrule" && /keyframes$/i.test(rule.parent.name)) return;
    rule.selector = splitSelectors(rule.selector).map((part) => scopeSelector(part, namespace)).join(", ");
  });
  root.walkAtRules(/keyframes$/, (rule) => { rule.params = `v2-${rule.params}`; });
  root.walkDecls(/^animation(?:-name)?$/, (declaration) => {
    declaration.value = declaration.value.replace(/\b(pulse|blink|spin)\b/g, "v2-$1");
  });
  return root.toString();
}

const sections = [await transform("globals", null)];
for (const [file, namespace] of modules) sections.push(await transform(file, namespace));
await writeFile(output, `/* Generated by scripts/build-v2-design.mjs; edit styles/v2-source instead. */\n${sections.join("\n\n")}`);
